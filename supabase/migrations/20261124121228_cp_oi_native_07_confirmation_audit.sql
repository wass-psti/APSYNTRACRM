-- CP07 additive client-generated PDF audit; no existing order or policy changes.
BEGIN;
CREATE TABLE public.order_intake_confirmation_audit (
 id uuid PRIMARY KEY,
 workspace_id uuid NOT NULL REFERENCES public.workspaces(id),
 order_id uuid NOT NULL,
 record_kind text NOT NULL CHECK(record_kind IN ('native','legacy')),
 order_revision integer NOT NULL CHECK(order_revision>0),
 generated_by uuid NOT NULL DEFAULT auth.uid(),
 generated_at timestamptz NOT NULL DEFAULT now(),
 pdf_sha256 text NOT NULL CHECK(pdf_sha256 ~ '^[0-9a-f]{64}$'),
 metadata jsonb NOT NULL CHECK(jsonb_typeof(metadata)='object' AND octet_length(metadata::text)<=12000)
);
CREATE INDEX oi_confirmation_audit_order ON public.order_intake_confirmation_audit(workspace_id,order_id,generated_at DESC,id DESC);
ALTER TABLE public.order_intake_confirmation_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.order_intake_confirmation_audit FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.order_intake_confirmation_audit TO authenticated;
GRANT INSERT(id,workspace_id,order_id,record_kind,order_revision,pdf_sha256,metadata) ON public.order_intake_confirmation_audit TO authenticated;
CREATE POLICY oi_confirmation_read ON public.order_intake_confirmation_audit FOR SELECT TO authenticated USING (
 workspace_id=(SELECT public.current_workspace_id((SELECT auth.uid())))
 AND (SELECT public.has_module_access('order-intake',(SELECT auth.uid()))));
CREATE POLICY oi_confirmation_append ON public.order_intake_confirmation_audit FOR INSERT TO authenticated WITH CHECK (
 generated_by=(SELECT auth.uid()) AND workspace_id=(SELECT public.current_workspace_id((SELECT auth.uid())))
 AND (SELECT public.has_module_access('order-intake',(SELECT auth.uid())))
 AND EXISTS(SELECT 1 FROM public.order_intake_operational_registry r
 WHERE r.id=order_intake_confirmation_audit.order_id AND r.workspace_id=order_intake_confirmation_audit.workspace_id
 AND r.record_kind=order_intake_confirmation_audit.record_kind AND r.revision=order_intake_confirmation_audit.order_revision));
-- Invoker, with existing registry visibility; client digest describes generated bytes,
-- not evidence of delivery, authorization of the signatory, or cryptographic signing.
CREATE FUNCTION public.order_intake_record_confirmation(p_id uuid,p_order_id uuid,p_kind text,p_revision integer,p_sha256 text,p_metadata jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog,public AS $$
DECLARE w uuid:=public.current_workspace_id(auth.uid()); r public.order_intake_confirmation_audit%ROWTYPE;
BEGIN
 IF auth.uid() IS NULL OR w IS NULL THEN RAISE EXCEPTION 'ORDER_INTAKE_CONTEXT_REQUIRED'; END IF;
 SELECT * INTO r FROM public.order_intake_confirmation_audit WHERE id=p_id;
 IF NOT FOUND THEN
  INSERT INTO public.order_intake_confirmation_audit(id,workspace_id,order_id,record_kind,order_revision,pdf_sha256,metadata)
  VALUES(p_id,w,p_order_id,p_kind,p_revision,p_sha256,p_metadata) ON CONFLICT(id) DO NOTHING;
  SELECT * INTO r FROM public.order_intake_confirmation_audit WHERE id=p_id;
 END IF;
 IF NOT FOUND OR r.workspace_id IS DISTINCT FROM w OR r.generated_by IS DISTINCT FROM auth.uid()
 OR r.order_id IS DISTINCT FROM p_order_id OR r.record_kind IS DISTINCT FROM p_kind
 OR r.order_revision IS DISTINCT FROM p_revision OR r.pdf_sha256 IS DISTINCT FROM p_sha256 OR r.metadata IS DISTINCT FROM p_metadata
 THEN RAISE EXCEPTION 'ORDER_INTAKE_CONFIRMATION_RECEIPT_CONFLICT'; END IF;
 RETURN jsonb_build_object('id',r.id,'sha256',r.pdf_sha256,'generatedAt',r.generated_at);
END $$;
REVOKE ALL ON FUNCTION public.order_intake_record_confirmation(uuid,uuid,text,integer,text,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.order_intake_record_confirmation(uuid,uuid,text,integer,text,jsonb) TO authenticated;
COMMIT;
