CREATE OR REPLACE FUNCTION private.tt_attendance_admin_apply_patch(
  p_record jsonb,
  p_patch jsonb,
  p_actor uuid,
  p_workspace uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path TO ''
AS $function$
DECLARE
  v_record jsonb := p_record;
  v_clock_in jsonb := p_record->'clockIn';
  v_clock_out jsonb := p_record->'clockOut';
  v_geo jsonb;
  v_key text;
  v_employee uuid;
  v_employee_name text;
  v_location text;
  v_department text;
  v_status text;
  v_time timestamptz;
  v_start timestamptz;
  v_end timestamptz;
  v_duration bigint;
  v_time_changed boolean := false;
BEGIN
  IF p_record IS NULL OR pg_catalog.jsonb_typeof(p_record) <> 'object'
     OR p_patch IS NULL OR pg_catalog.jsonb_typeof(p_patch) <> 'object'
     OR p_actor IS NULL OR p_workspace IS NULL THEN
    RAISE EXCEPTION 'Attendance correction payload is invalid' USING ERRCODE='22023';
  END IF;
  IF p_patch = '{}'::jsonb THEN
    RAISE EXCEPTION 'At least one attendance field must be changed' USING ERRCODE='22023';
  END IF;

  FOR v_key IN SELECT pg_catalog.jsonb_object_keys(p_patch) LOOP
    IF v_key NOT IN (
      'employeeId','location','department','clockInAt','clockInGeo',
      'clockOutAt','clockOutGeo','status','creditedMsOverride'
    ) THEN
      RAISE EXCEPTION 'Unsupported attendance correction field: %', v_key
        USING ERRCODE='22023';
    END IF;
  END LOOP;

  IF p_patch ? 'employeeId' THEN
    IF COALESCE(p_patch->>'employeeId','') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' THEN
      RAISE EXCEPTION 'Selected employee identity is invalid' USING ERRCODE='22023';
    END IF;
    v_employee := (p_patch->>'employeeId')::uuid;
    SELECT COALESCE(NULLIF(pg_catalog.btrim(p.display_name),''),p.email,'Workforce member')
      INTO v_employee_name
    FROM public.profiles p
    JOIN public.workspace_members wm
      ON wm.user_id=p.id AND wm.workspace_id=p_workspace AND wm.active=true
    WHERE p.id=v_employee AND p.status='active'
      AND public.has_module_access('time-tracker',p.id);
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Selected employee is not active in this TimeTracker workspace'
        USING ERRCODE='22023';
    END IF;
    v_record := pg_catalog.jsonb_set(v_record,ARRAY['ownerId'],
      pg_catalog.to_jsonb('cloud:'||v_employee::text),true);
    v_record := pg_catalog.jsonb_set(v_record,ARRAY['ownerName'],
      pg_catalog.to_jsonb(v_employee_name),true);
  END IF;

  IF p_patch ? 'location' THEN
    v_location := p_patch->>'location';
    IF v_location IS NULL OR v_location NOT IN (
      'Office-Base Duty','Offsite (Home)','Local Field Works',
      'Out of Town Assignment','International Field Assignments'
    ) THEN
      RAISE EXCEPTION 'Attendance work location is invalid' USING ERRCODE='22023';
    END IF;
    v_clock_in := pg_catalog.jsonb_set(v_clock_in,ARRAY['location'],pg_catalog.to_jsonb(v_location),true);
    IF pg_catalog.jsonb_typeof(v_clock_out)='object' THEN
      v_clock_out := pg_catalog.jsonb_set(v_clock_out,ARRAY['location'],pg_catalog.to_jsonb(v_location),true);
    END IF;
  END IF;

  IF p_patch ? 'department' THEN
    v_department := p_patch->>'department';
    IF v_department IS NULL OR v_department NOT IN (
      'HR','Materials and Logistics','Engineering','Finance and Accounting',
      'Sales and Marketing','Information Technology'
    ) THEN
      RAISE EXCEPTION 'Attendance department is invalid' USING ERRCODE='22023';
    END IF;
    v_clock_in := pg_catalog.jsonb_set(v_clock_in,ARRAY['department'],pg_catalog.to_jsonb(v_department),true);
    IF pg_catalog.jsonb_typeof(v_clock_out)='object' THEN
      v_clock_out := pg_catalog.jsonb_set(v_clock_out,ARRAY['department'],pg_catalog.to_jsonb(v_department),true);
    END IF;
  END IF;

  IF p_patch ? 'clockInAt' THEN
    BEGIN
      v_time := (p_patch->>'clockInAt')::timestamptz;
    EXCEPTION WHEN OTHERS THEN
      RAISE EXCEPTION 'Clock-In timestamp is invalid' USING ERRCODE='22023';
    END;
    IF v_time IS NULL THEN RAISE EXCEPTION 'Clock-In timestamp is required' USING ERRCODE='22023'; END IF;
    v_clock_in := pg_catalog.jsonb_set(v_clock_in,ARRAY['timestamp'],pg_catalog.to_jsonb(v_time),true);
    v_time_changed := true;
  END IF;

  IF p_patch ? 'clockInGeo' THEN
    v_geo := p_patch->'clockInGeo';
    IF pg_catalog.jsonb_typeof(v_geo)<>'object'
       OR pg_catalog.jsonb_typeof(v_geo->'latitude')<>'number'
       OR pg_catalog.jsonb_typeof(v_geo->'longitude')<>'number'
       OR pg_catalog.jsonb_typeof(v_geo->'accuracy')<>'number'
       OR (v_geo->>'latitude')::numeric NOT BETWEEN -90 AND 90
       OR (v_geo->>'longitude')::numeric NOT BETWEEN -180 AND 180
       OR (v_geo->>'accuracy')::numeric NOT BETWEEN 0 AND 100000 THEN
      RAISE EXCEPTION 'Clock-In GPS correction is invalid' USING ERRCODE='22023';
    END IF;
    v_geo := v_geo || pg_catalog.jsonb_build_object(
      'status','captured','source','administrative-correction',
      'correctedAt',pg_catalog.clock_timestamp(),'correctedBy',p_actor::text
    );
    v_clock_in := pg_catalog.jsonb_set(v_clock_in,ARRAY['geo'],v_geo,true);
  END IF;

  IF p_patch ? 'clockOutAt' THEN
    BEGIN
      v_time := (p_patch->>'clockOutAt')::timestamptz;
    EXCEPTION WHEN OTHERS THEN
      RAISE EXCEPTION 'Clock-Out timestamp is invalid' USING ERRCODE='22023';
    END;
    IF v_time IS NULL THEN RAISE EXCEPTION 'Clock-Out timestamp is required' USING ERRCODE='22023'; END IF;
    IF pg_catalog.jsonb_typeof(v_clock_out)<>'object' THEN
      v_clock_out := pg_catalog.jsonb_build_object(
        'location',COALESCE(v_clock_in->>'location',''),
        'department',COALESCE(v_clock_in->>'department','')
      );
    END IF;
    v_clock_out := pg_catalog.jsonb_set(v_clock_out,ARRAY['timestamp'],pg_catalog.to_jsonb(v_time),true);
    v_time_changed := true;
  END IF;

  IF p_patch ? 'clockOutGeo' THEN
    v_geo := p_patch->'clockOutGeo';
    IF pg_catalog.jsonb_typeof(v_geo)<>'object'
       OR pg_catalog.jsonb_typeof(v_geo->'latitude')<>'number'
       OR pg_catalog.jsonb_typeof(v_geo->'longitude')<>'number'
       OR pg_catalog.jsonb_typeof(v_geo->'accuracy')<>'number'
       OR (v_geo->>'latitude')::numeric NOT BETWEEN -90 AND 90
       OR (v_geo->>'longitude')::numeric NOT BETWEEN -180 AND 180
       OR (v_geo->>'accuracy')::numeric NOT BETWEEN 0 AND 100000 THEN
      RAISE EXCEPTION 'Clock-Out GPS correction is invalid' USING ERRCODE='22023';
    END IF;
    v_geo := v_geo || pg_catalog.jsonb_build_object(
      'status','captured','source','administrative-correction',
      'correctedAt',pg_catalog.clock_timestamp(),'correctedBy',p_actor::text
    );
    IF pg_catalog.jsonb_typeof(v_clock_out)<>'object' THEN
      v_clock_out := pg_catalog.jsonb_build_object(
        'location',COALESCE(v_clock_in->>'location',''),
        'department',COALESCE(v_clock_in->>'department','')
      );
    END IF;
    v_clock_out := pg_catalog.jsonb_set(v_clock_out,ARRAY['geo'],v_geo,true);
  END IF;

  v_status := p_patch->>'status';
  IF v_status IS NULL AND (p_patch ? 'clockOutAt' OR p_patch ? 'clockOutGeo') THEN
    v_status := 'Completed';
  END IF;
  IF (p_patch ? 'status' AND v_status IS NULL) OR (v_status IS NOT NULL AND v_status NOT IN ('Active','Completed')) THEN
    RAISE EXCEPTION 'Attendance status must be Active or Completed' USING ERRCODE='22023';
  END IF;
  IF v_status='Active' THEN
    IF p_patch ? 'clockOutAt' OR p_patch ? 'clockOutGeo' THEN
      RAISE EXCEPTION 'Clock-Out fields cannot be changed while setting status to Active' USING ERRCODE='22023';
    END IF;
    v_clock_out := 'null'::jsonb;
  ELSIF v_status='Completed' AND pg_catalog.jsonb_typeof(v_clock_out)<>'object' THEN
    RAISE EXCEPTION 'Clock-Out timestamp and GPS are required to complete an active record' USING ERRCODE='22023';
  END IF;

  v_record := pg_catalog.jsonb_set(v_record,ARRAY['clockIn'],v_clock_in,true);
  v_record := pg_catalog.jsonb_set(v_record,ARRAY['clockOut'],COALESCE(v_clock_out,'null'::jsonb),true);

  BEGIN
    v_start := (v_clock_in->>'timestamp')::timestamptz;
    IF pg_catalog.jsonb_typeof(v_clock_out)='object' THEN
      v_end := (v_clock_out->>'timestamp')::timestamptz;
      IF v_end IS NULL OR v_end<v_start THEN
        RAISE EXCEPTION 'Clock-Out must be at or after Clock-In' USING ERRCODE='22023';
      END IF;
    ELSE
      v_end := NULL;
    END IF;
  EXCEPTION WHEN OTHERS THEN
    IF SQLSTATE='22023' THEN RAISE; END IF;
    RAISE EXCEPTION 'Attendance timestamps are invalid' USING ERRCODE='22023';
  END;
  IF v_start IS NULL THEN RAISE EXCEPTION 'Clock-In timestamp is required' USING ERRCODE='22023'; END IF;
  IF v_end IS NOT NULL AND v_end>v_start+INTERVAL '370 days' THEN
    RAISE EXCEPTION 'Attendance duration exceeds the supported policy window' USING ERRCODE='22023';
  END IF;
  IF pg_catalog.jsonb_typeof(v_clock_out)='object'
     AND (p_patch ? 'status' OR p_patch ? 'clockOutAt' OR p_patch ? 'clockOutGeo')
     AND (pg_catalog.jsonb_typeof(v_clock_out->'geo')<>'object'
       OR v_clock_out#>>'{geo,status}'<>'captured') THEN
    RAISE EXCEPTION 'Completed attendance requires a recorded Clock-Out GPS fix' USING ERRCODE='22023';
  END IF;

  IF p_patch ? 'creditedMsOverride' THEN
    IF p_patch->'creditedMsOverride'='null'::jsonb THEN
      v_record := v_record - 'creditedMsOverride';
    ELSE
      IF v_end IS NULL OR pg_catalog.jsonb_typeof(p_patch->'creditedMsOverride')<>'number' THEN
        RAISE EXCEPTION 'Manual working duration requires a completed attendance record' USING ERRCODE='22023';
      END IF;
      v_duration := (p_patch->>'creditedMsOverride')::bigint;
      IF v_duration<0 OR v_duration>2678400000 THEN
        RAISE EXCEPTION 'Working duration must be between zero and 744 hours' USING ERRCODE='22023';
      END IF;
      v_record := pg_catalog.jsonb_set(v_record,ARRAY['creditedMsOverride'],pg_catalog.to_jsonb(v_duration),true);
    END IF;
  ELSIF v_time_changed OR v_end IS NULL THEN
    -- Time corrections recalculate credited duration unless a manual override
    -- was explicitly supplied in the same edit. Active records never retain it.
    v_record := v_record - 'creditedMsOverride';
  END IF;

  RETURN pg_catalog.jsonb_set(v_record,ARRAY['updatedAt'],
    pg_catalog.to_jsonb(pg_catalog.clock_timestamp()),true);
END;
$function$;
REVOKE ALL ON FUNCTION private.tt_attendance_admin_apply_patch(jsonb,jsonb,uuid,uuid) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.tt_attendance_admin_sync_projection(
  p_board_id uuid,
  p_workspace_id uuid,
  p_actor uuid,
  p_record jsonb,
  p_revision bigint
)
RETURNS void
LANGUAGE plpgsql
SET search_path TO ''
AS $function$
DECLARE
  v_record_id uuid;
  v_employee uuid;
  v_item uuid;
  v_clock_in timestamptz;
  v_clock_out timestamptz;
  v_in_geo jsonb;
  v_out_geo jsonb;
  v_credited bigint;
  v_hours numeric;
  v_status text;
  v_column record;
  v_value jsonb;
  v_label text;
  v_label_id text;
  v_count integer;
BEGIN
  IF COALESCE(p_record->>'id','') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
     OR COALESCE(p_record->>'ownerId','') !~* '^cloud:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
    RAISE EXCEPTION 'Attendance projection identity is invalid' USING ERRCODE='22023';
  END IF;
  v_record_id := (p_record->>'id')::uuid;
  v_employee := pg_catalog.substr(p_record->>'ownerId',7)::uuid;
  v_clock_in := (p_record#>>'{clockIn,timestamp}')::timestamptz;
  v_in_geo := p_record#>'{clockIn,geo}';
  IF pg_catalog.jsonb_typeof(v_in_geo)<>'object' OR v_in_geo->>'status'<>'captured' THEN
    RAISE EXCEPTION 'Clock-In GPS evidence is required for projected attendance' USING ERRCODE='22023';
  END IF;
  IF pg_catalog.jsonb_typeof(p_record->'clockOut')='object' THEN
    v_clock_out := (p_record#>>'{clockOut,timestamp}')::timestamptz;
    v_out_geo := p_record#>'{clockOut,geo}';
    IF v_clock_out IS NULL OR pg_catalog.jsonb_typeof(v_out_geo)<>'object'
       OR v_out_geo->>'status'<>'captured' THEN
      RAISE EXCEPTION 'Clock-Out GPS evidence is required for completed projected attendance' USING ERRCODE='22023';
    END IF;
  ELSE
    v_clock_out := NULL;
    v_out_geo := NULL;
  END IF;
  IF v_clock_in IS NULL OR (v_clock_out IS NOT NULL AND v_clock_out<v_clock_in) THEN
    RAISE EXCEPTION 'Attendance projection timestamps are invalid' USING ERRCODE='22023';
  END IF;
  v_credited := CASE WHEN v_clock_out IS NULL THEN NULL
    ELSE COALESCE((p_record->>'creditedMsOverride')::bigint,
      private.tt_attendance_credited_ms(v_clock_in,v_clock_out)) END;
  IF v_credited IS NOT NULL AND v_credited<0 THEN
    RAISE EXCEPTION 'Attendance credited duration is invalid' USING ERRCODE='22023';
  END IF;
  v_hours := CASE WHEN v_credited IS NULL THEN NULL
    ELSE pg_catalog.round(v_credited::numeric/3600000,2) END;
  v_status := CASE WHEN v_clock_out IS NULL THEN 'in_progress' ELSE 'done' END;

  SELECT board_item_id INTO v_item
  FROM private.tt_attendance_board_projection
  WHERE board_id=p_board_id AND workspace_id=p_workspace_id AND record_id=v_record_id
  FOR UPDATE;
  IF NOT FOUND THEN RETURN; END IF; -- Legacy records may predate the board projection.

  UPDATE private.tt_attendance_board_projection SET
    employee_id=v_employee,source_revision=p_revision,
    clock_in_at=v_clock_in,clock_out_at=v_clock_out,
    clock_in_geo=v_in_geo,clock_out_geo=v_out_geo,
    clock_in_location=pg_catalog.left(COALESCE(p_record#>>'{clockIn,location}',''),100),
    clock_out_location=pg_catalog.left(COALESCE(p_record#>>'{clockOut,location}',''),100),
    credited_ms=v_credited,modified_at=pg_catalog.clock_timestamp()
  WHERE board_id=p_board_id AND record_id=v_record_id;

  UPDATE public.work_board_items SET status=v_status,updated_by=p_actor,
    updated_at=pg_catalog.clock_timestamp()
  WHERE id=v_item AND board_id=p_board_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Attendance board projection item is missing' USING ERRCODE='23503'; END IF;

  SELECT pg_catalog.count(*) INTO v_count
  FROM public.work_board_columns c WHERE c.board_id=p_board_id
    AND c.name IN ('Source Record ID','Source Revision','Sync State','Attendance Ref',
      'Attendance Date','Hours Total','Attendance Status','Shift Ref');
  IF v_count<>8 THEN RAISE EXCEPTION 'Attendance board typed column contract drift' USING ERRCODE='23503'; END IF;

  FOR v_column IN
    SELECT c.id,c.name,c.config FROM public.work_board_columns c
    WHERE c.board_id=p_board_id AND c.name IN (
      'Source Record ID','Source Revision','Sync State','Attendance Ref',
      'Attendance Date','Hours Total','Attendance Status','Shift Ref')
  LOOP
    v_value := NULL;
    v_label := NULL;
    v_label_id := NULL;
    CASE v_column.name
      WHEN 'Source Record ID' THEN v_value:=pg_catalog.to_jsonb(v_record_id::text);
      WHEN 'Source Revision' THEN v_value:=pg_catalog.to_jsonb(p_revision);
      WHEN 'Attendance Ref' THEN v_value:=pg_catalog.to_jsonb(v_record_id::text);
      WHEN 'Attendance Date' THEN v_value:=pg_catalog.to_jsonb((v_clock_in AT TIME ZONE 'Asia/Manila')::date::text);
      WHEN 'Hours Total' THEN IF v_hours IS NOT NULL THEN v_value:=pg_catalog.to_jsonb(v_hours); END IF;
      WHEN 'Sync State' THEN v_label:='Synchronized';
      WHEN 'Attendance Status' THEN v_label:=CASE WHEN v_clock_out IS NULL THEN 'In progress' ELSE 'Done' END;
      ELSE NULL;
    END CASE;
    IF v_label IS NOT NULL THEN
      SELECT label->>'id' INTO v_label_id
      FROM pg_catalog.jsonb_array_elements(COALESCE(v_column.config->'labels','[]'::jsonb)) label
      WHERE label->>'name'=v_label LIMIT 1;
      IF v_label_id IS NULL THEN RAISE EXCEPTION 'Attendance board label contract drift' USING ERRCODE='23503'; END IF;
      v_value:=pg_catalog.to_jsonb(v_label_id);
    END IF;
    IF v_value IS NULL THEN
      DELETE FROM public.work_board_item_values WHERE item_id=v_item AND column_id=v_column.id;
    ELSE
      INSERT INTO public.work_board_item_values(item_id,column_id,value,updated_by)
      VALUES(v_item,v_column.id,v_value,p_actor)
      ON CONFLICT(item_id,column_id) DO UPDATE SET
        value=EXCLUDED.value,updated_by=EXCLUDED.updated_by,
        updated_at=pg_catalog.clock_timestamp();
    END IF;
  END LOOP;
END;
$function$;
REVOKE ALL ON FUNCTION private.tt_attendance_admin_sync_projection(uuid,uuid,uuid,jsonb,bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.timetracker_attendance_admin_snapshot(
  p_board_id uuid,
  p_record_ids text[]
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_workspace uuid;
  v_role text;
  v_value text;
  v_revision bigint;
  v_state jsonb;
  v_records jsonb;
  v_count integer;
  v_directory jsonb;
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'A signed CRM session is required' USING ERRCODE='42501'; END IF;
  v_workspace := public.timetracker_ot_require_scope(p_board_id);
  v_role := public.module_role_for('time-tracker',v_actor);
  IF v_role IS DISTINCT FROM 'System Admin' THEN
    RAISE EXCEPTION 'System Admin attendance management required' USING ERRCODE='42501';
  END IF;
  IF p_record_ids IS NULL OR pg_catalog.cardinality(p_record_ids) NOT BETWEEN 1 AND 100
     OR EXISTS (SELECT 1 FROM pg_catalog.unnest(p_record_ids) id
       WHERE COALESCE(id,'') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
     OR (SELECT pg_catalog.count(*) FROM pg_catalog.unnest(p_record_ids)) <>
        (SELECT pg_catalog.count(DISTINCT id) FROM pg_catalog.unnest(p_record_ids) id) THEN
    RAISE EXCEPTION 'Attendance record selection is invalid' USING ERRCODE='22023';
  END IF;
  SELECT e.value,e.revision INTO v_value,v_revision
  FROM public.module_state_entries e
  WHERE e.workspace_id=v_workspace AND e.module_id='time-tracker'
    AND e.state_key='timetracker.attendance.v1' AND e.scope='shared' AND e.owner_key='*';
  IF v_value IS NULL THEN RAISE EXCEPTION 'Attendance state is unavailable' USING ERRCODE='P0002'; END IF;
  BEGIN v_state:=v_value::jsonb; EXCEPTION WHEN OTHERS THEN
    RAISE EXCEPTION 'Attendance state is malformed' USING ERRCODE='22023'; END;
  IF v_state->>'version'<>'1' OR pg_catalog.jsonb_typeof(v_state->'records')<>'array' THEN
    RAISE EXCEPTION 'Attendance state contract is invalid' USING ERRCODE='22023';
  END IF;
  SELECT pg_catalog.jsonb_agg(r.value ORDER BY r.ordinality),pg_catalog.count(*)
    INTO v_records,v_count
  FROM pg_catalog.jsonb_array_elements(v_state->'records') WITH ORDINALITY r(value,ordinality)
  WHERE r.value->>'id'=ANY(p_record_ids);
  IF v_count<>pg_catalog.cardinality(p_record_ids) THEN
    RAISE EXCEPTION 'One or more selected attendance records no longer exist' USING ERRCODE='P0002';
  END IF;
  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
    'id',p.id,'displayName',COALESCE(NULLIF(pg_catalog.btrim(p.display_name),''),p.email,'Workforce member')
  ) ORDER BY pg_catalog.lower(COALESCE(p.display_name,p.email))), '[]'::jsonb)
  INTO v_directory
  FROM public.profiles p
  JOIN public.workspace_members wm ON wm.user_id=p.id AND wm.workspace_id=v_workspace AND wm.active=true
  WHERE p.status='active' AND public.has_module_access('time-tracker',p.id);

  RETURN pg_catalog.jsonb_build_object(
    'mode','ACTIVE','contract','tt-attendance-admin-1',
    'actorId',v_actor::text,'workspaceId',v_workspace::text,'boardId',p_board_id::text,
    'revision',v_revision,'records',COALESCE(v_records,'[]'::jsonb),
    'directory',v_directory
  );
END;
$function$;
REVOKE ALL ON FUNCTION public.timetracker_attendance_admin_snapshot(uuid,text[]) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.timetracker_attendance_admin_snapshot(uuid,text[]) TO authenticated;

CREATE OR REPLACE FUNCTION public.timetracker_attendance_admin_mutate(
  p_board_id uuid,
  p_action text,
  p_record_ids text[],
  p_patch jsonb,
  p_reason text,
  p_expected_revision bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_workspace uuid;
  v_role text;
  v_current_value text;
  v_current_revision bigint;
  v_new_revision bigint;
  v_state jsonb;
  v_updated_state jsonb;
  v_updated_records jsonb;
  v_before_records jsonb;
  v_after_records jsonb;
  v_record jsonb;
  v_item uuid;
  v_count integer;
  v_deleted integer := 0;
  v_reason text := NULLIF(pg_catalog.btrim(p_reason),'');
  v_committed_at timestamptz := pg_catalog.clock_timestamp();
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'A signed CRM session is required' USING ERRCODE='42501'; END IF;
  v_workspace := public.timetracker_ot_require_scope(p_board_id);
  v_role := public.module_role_for('time-tracker',v_actor);
  IF v_role IS DISTINCT FROM 'System Admin' THEN
    RAISE EXCEPTION 'System Admin attendance management required' USING ERRCODE='42501';
  END IF;
  IF p_action NOT IN ('edit','bulk-edit','delete','bulk-delete') OR p_action IS NULL THEN
    RAISE EXCEPTION 'Unsupported attendance management action' USING ERRCODE='22023';
  END IF;
  IF p_record_ids IS NULL OR pg_catalog.cardinality(p_record_ids) NOT BETWEEN 1 AND 100
     OR EXISTS (SELECT 1 FROM pg_catalog.unnest(p_record_ids) id
       WHERE COALESCE(id,'') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
     OR (SELECT pg_catalog.count(*) FROM pg_catalog.unnest(p_record_ids)) <>
        (SELECT pg_catalog.count(DISTINCT id) FROM pg_catalog.unnest(p_record_ids) id) THEN
    RAISE EXCEPTION 'Attendance record selection is invalid' USING ERRCODE='22023';
  END IF;
  IF p_action IN ('edit','delete') AND pg_catalog.cardinality(p_record_ids)<>1 THEN
    RAISE EXCEPTION 'Individual attendance actions require exactly one record' USING ERRCODE='22023';
  END IF;
  IF p_action IN ('bulk-edit','bulk-delete') AND pg_catalog.cardinality(p_record_ids)<1 THEN
    RAISE EXCEPTION 'At least one attendance record must be selected' USING ERRCODE='22023';
  END IF;
  IF p_action IN ('edit','bulk-edit') AND
     (p_patch IS NULL OR pg_catalog.jsonb_typeof(p_patch)<>'object'
       OR p_patch='{}'::jsonb OR pg_catalog.octet_length(p_patch::text)>65536) THEN
    RAISE EXCEPTION 'Attendance correction fields are empty or invalid' USING ERRCODE='22023';
  END IF;
  IF p_action IN ('delete','bulk-delete') AND COALESCE(p_patch,'{}'::jsonb)<>'{}'::jsonb THEN
    RAISE EXCEPTION 'Delete actions do not accept an edit payload' USING ERRCODE='22023';
  END IF;
  IF pg_catalog.length(COALESCE(v_reason,''))>500 THEN
    RAISE EXCEPTION 'Attendance correction reason exceeds 500 characters' USING ERRCODE='22023';
  END IF;
  IF p_expected_revision IS NULL OR p_expected_revision<1 THEN
    RAISE EXCEPTION 'Current attendance revision is required' USING ERRCODE='22023';
  END IF;

  SELECT e.value,e.revision INTO v_current_value,v_current_revision
  FROM public.module_state_entries e
  WHERE e.workspace_id=v_workspace AND e.module_id='time-tracker'
    AND e.state_key='timetracker.attendance.v1' AND e.scope='shared' AND e.owner_key='*'
  FOR UPDATE;
  IF v_current_value IS NULL THEN RAISE EXCEPTION 'Attendance state is unavailable' USING ERRCODE='P0002'; END IF;
  IF v_current_revision<>p_expected_revision THEN
    RAISE EXCEPTION 'TT_ATTENDANCE_REVISION_CONFLICT expected %, current %',p_expected_revision,v_current_revision
      USING ERRCODE='40001';
  END IF;
  BEGIN v_state:=v_current_value::jsonb; EXCEPTION WHEN OTHERS THEN
    RAISE EXCEPTION 'Attendance state is malformed' USING ERRCODE='22023'; END;
  IF v_state->>'version'<>'1' OR pg_catalog.jsonb_typeof(v_state->'records')<>'array'
     OR pg_catalog.jsonb_array_length(v_state->'records')>25000 THEN
    RAISE EXCEPTION 'Attendance state contract is invalid' USING ERRCODE='22023';
  END IF;

  SELECT pg_catalog.jsonb_agg(r.value ORDER BY r.ordinality),pg_catalog.count(*)
    INTO v_before_records,v_count
  FROM pg_catalog.jsonb_array_elements(v_state->'records') WITH ORDINALITY r(value,ordinality)
  WHERE r.value->>'id'=ANY(p_record_ids);
  IF v_count<>pg_catalog.cardinality(p_record_ids) THEN
    RAISE EXCEPTION 'One or more selected attendance records no longer exist' USING ERRCODE='P0002';
  END IF;

  IF p_action IN ('edit','bulk-edit') THEN
    SELECT COALESCE(pg_catalog.jsonb_agg(
      CASE WHEN r.value->>'id'=ANY(p_record_ids)
        THEN private.tt_attendance_admin_apply_patch(r.value,p_patch,v_actor,v_workspace)
        ELSE r.value END
      ORDER BY r.ordinality),'[]'::jsonb)
    INTO v_updated_records
    FROM pg_catalog.jsonb_array_elements(v_state->'records') WITH ORDINALITY r(value,ordinality);

    SELECT pg_catalog.jsonb_agg(r.value ORDER BY r.ordinality)
    INTO v_after_records
    FROM pg_catalog.jsonb_array_elements(v_updated_records) WITH ORDINALITY r(value,ordinality)
    WHERE r.value->>'id'=ANY(p_record_ids);
  ELSE
    SELECT COALESCE(pg_catalog.jsonb_agg(r.value ORDER BY r.ordinality),'[]'::jsonb)
    INTO v_updated_records
    FROM pg_catalog.jsonb_array_elements(v_state->'records') WITH ORDINALITY r(value,ordinality)
    WHERE NOT (r.value->>'id'=ANY(p_record_ids));
    v_after_records := '[]'::jsonb;
    v_deleted := pg_catalog.cardinality(p_record_ids);
  END IF;

  v_updated_state := pg_catalog.jsonb_set(v_state,ARRAY['records'],v_updated_records,true);
  IF NOT public.module_state_invariants_valid('time-tracker','timetracker.attendance.v1',v_updated_state::text) THEN
    RAISE EXCEPTION 'Attendance management mutation violates record integrity or active-session invariants'
      USING ERRCODE='23514';
  END IF;

  -- Preserve the existing rolling recovery copy and revision contract.
  INSERT INTO public.module_state_entries(
    workspace_id,module_id,state_key,scope,owner_key,value,revision,updated_by,updated_at
  ) VALUES(v_workspace,'time-tracker','timetracker.attendance.v1.backup','shared','*',
    v_current_value,1,v_actor,v_committed_at)
  ON CONFLICT ON CONSTRAINT module_state_entries_pkey DO UPDATE SET
    value=EXCLUDED.value,revision=public.module_state_entries.revision+1,
    updated_by=v_actor,updated_at=v_committed_at;

  UPDATE public.module_state_entries SET value=v_updated_state::text,
    revision=revision+1,updated_by=v_actor,updated_at=v_committed_at
  WHERE workspace_id=v_workspace AND module_id='time-tracker'
    AND state_key='timetracker.attendance.v1' AND scope='shared' AND owner_key='*'
  RETURNING revision INTO v_new_revision;
  IF v_new_revision IS NULL OR v_new_revision<=v_current_revision THEN
    RAISE EXCEPTION 'Attendance management revision was not committed' USING ERRCODE='40001';
  END IF;

  IF p_action IN ('edit','bulk-edit') THEN
    FOR v_record IN SELECT r.value
      FROM pg_catalog.jsonb_array_elements(v_after_records) r(value)
    LOOP
      PERFORM private.tt_attendance_admin_sync_projection(
        p_board_id,v_workspace,v_actor,v_record,v_new_revision);
    END LOOP;
  ELSE
    FOR v_record IN SELECT r.value
      FROM pg_catalog.jsonb_array_elements(v_before_records) r(value)
    LOOP
      IF COALESCE(v_record->>'id','') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
        SELECT p.board_item_id INTO v_item
        FROM private.tt_attendance_board_projection p
        WHERE p.board_id=p_board_id AND p.workspace_id=v_workspace
          AND p.record_id=(v_record->>'id')::uuid
        FOR UPDATE;
        IF FOUND THEN
          DELETE FROM private.tt_attendance_board_projection
          WHERE board_id=p_board_id AND record_id=(v_record->>'id')::uuid;
          DELETE FROM public.work_board_items WHERE id=v_item AND board_id=p_board_id;
          IF NOT FOUND THEN RAISE EXCEPTION 'Attendance board projection item is missing during deletion' USING ERRCODE='23503'; END IF;
        END IF;
      END IF;
    END LOOP;
  END IF;

  INSERT INTO private.tt_attendance_admin_audit(
    workspace_id,board_id,actor_id,action,record_ids,base_revision,
    committed_revision,before_records,after_records,reason,committed_at
  ) VALUES(
    v_workspace,p_board_id,v_actor,p_action,p_record_ids,v_current_revision,
    v_new_revision,v_before_records,v_after_records,v_reason,v_committed_at
  );

  RETURN pg_catalog.jsonb_build_object(
    'mode','COMMITTED','contract','tt-attendance-admin-1',
    'actorId',v_actor::text,'workspaceId',v_workspace::text,'boardId',p_board_id::text,
    'action',p_action,'recordIds',pg_catalog.to_jsonb(p_record_ids),
    'changedCount',CASE WHEN p_action IN ('edit','bulk-edit') THEN pg_catalog.cardinality(p_record_ids) ELSE 0 END,
    'deletedCount',v_deleted,'baseRevision',v_current_revision,
    'revision',v_new_revision,'committedAt',v_committed_at
  );
END;
$function$;
REVOKE ALL ON FUNCTION public.timetracker_attendance_admin_mutate(uuid,text,text[],jsonb,text,bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.timetracker_attendance_admin_mutate(uuid,text,text[],jsonb,text,bigint) TO authenticated;

COMMIT;
