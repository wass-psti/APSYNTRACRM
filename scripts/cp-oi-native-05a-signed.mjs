import assert from 'node:assert/strict';
import {OrderIntakeOperationalClient} from '../frontend/order-intake-operational-client.js';
import {saveLifecycle} from '../frontend/order-intake-lifecycle.js';
import {orderEditorDraft,createOrderEditorSave} from '../frontend/order-intake-editor.js';
import {notificationInbox,recipientFields} from '../frontend/order-intake-notifications.js';
import {renderOrderIntake} from '../frontend/order-intake-ui.js';
import {parseOrderIntakeRoute} from '../frontend/order-intake-route.js';
import {verifyOperationalBrowser} from './cp-oi-native-05a-browser.mjs';
import {randomUUID} from 'node:crypto';

export async function verifyOperationalLifecycle({auth,api,workspace,foreign,signin,sql,manifest}){
 const actor=new OrderIntakeOperationalClient({auth,api,workspaceId:workspace});
 const manager=await signin(workspace,true),other=await signin(workspace,true),outsider=await signin(foreign,true);
 const recipient=new OrderIntakeOperationalClient({auth:manager.auth,api:manager.api,workspaceId:workspace});
 const unrelated=new OrderIntakeOperationalClient({auth:other.auth,api:other.api,workspaceId:workspace});
 const cross=new OrderIntakeOperationalClient({auth:outsider.auth,api:outsider.api,workspaceId:foreign});
 const records=[];let more=true;
 while(more){const page=await actor.list({offset:records.length,limit:100});records.push(...page.items);more=page.hasMore;}
 const legacy=records.filter(r=>r.record_kind==='legacy');
 assert.equal(legacy.length,909);assert.equal(new Set(legacy.map(r=>r.id)).size,909);
 assert.ok(legacy.every(r=>r.revision===1&&r.archived===null&&r.source_archive_state===null));
 const sourceByKey=new Map(manifest.records.map(r=>[r.identity.key,r]));
 for(const row of legacy){const original=sourceByKey.get(row.source_key);assert.ok(original);assert.equal(row.source_status,original.sourceStatus);assert.equal(row.po_amount,original.values.poAmount);}
 const snapshotHash=sql("select md5(string_agg(id::text||':'||md5(payload::text),',' order by id)) from order_intake_legacy_orders");
 const original=legacy.find(row=>!['Delayed','Delivered','Collected','Closed','Cancelled'].includes(row.status));
 assert.ok(original);
 const before=sql("select md5(payload::text) from order_intake_legacy_orders where id='"+original.id+"'");
 let row=original;
 const move=async target=>{row=await saveLifecycle({client:actor,row,action:'status',target});assert.equal(row.status,target);};
 await move('Delayed');assert.equal(row.revision,2);assert.equal(row.archived,null);assert.equal(row.source_status,original.source_status);
 assert.equal((await actor.operationalActivity(row)).rows[0].delivery_state,'UNRESOLVED');
 assert.equal((await recipient.notifications()).rows.length,0);
 const directory=await actor.recipientOptions(row);
 assert.ok(directory.members.some(member=>member.id===manager.auth.userId));
 assert.ok(!directory.members.some(member=>member.id===outsider.auth.userId));
 assert.match(recipientFields(directory),/Confirm the workspace member/);
 await assert.rejects(actor.bindRecipient(row,outsider.auth.userId),/INVALID_RECIPIENT/);
 await assert.rejects(actor.bindRecipient(original,manager.auth.userId),/REVISION_CONFLICT/);
 await actor.bindRecipient(row,manager.auth.userId);
 await move('Delivered');assert.equal(row.revision,3);assert.equal(row.archived,null);
 await assert.rejects(actor.changeLegacy(original,'status','Processed'),/REVISION_CONFLICT/);
 await assert.rejects(cross.changeLegacy(row,'status','Processed'),/NOT_FOUND/);
 const inbox=await recipient.notifications();
 assert.equal(inbox.rows.length,1);assert.equal(inbox.rows[0].status,'Delivered');assert.equal(inbox.rows[0].read_at,null);
 assert.equal((await unrelated.notifications()).rows.length,0);assert.equal((await actor.notifications()).rows.length,0);
 await assert.rejects(unrelated.markNotificationRead(inbox.rows[0].id),/NOT_FOUND/);
 const receipt=await recipient.markNotificationRead(inbox.rows[0].id);
 assert.ok(receipt.readAt);assert.equal((await recipient.markNotificationRead(inbox.rows[0].id)).readAt,receipt.readAt);
 assert.equal((await recipient.notifications()).rows[0].read_at,receipt.readAt);
 assert.match(notificationInbox(await recipient.notifications()),/Read/);
 row=await saveLifecycle({client:actor,row,action:'archive'});
 assert.equal(row.archived,true);assert.equal(row.revision,4);
 assert.ok((await actor.list({archived:true})).items.some(r=>r.id===row.id));
 row=await saveLifecycle({client:actor,row,action:'restore'});
 assert.equal(row.archived,false);assert.equal(row.revision,5);assert.equal(row.source_archive_state,null);
 assert.equal(row.source_status,original.source_status);assert.equal(row.po_amount,original.po_amount);assert.equal(row.gross_profit,original.gross_profit);
 assert.equal(sql("select md5(payload::text) from order_intake_legacy_orders where id='"+row.id+"'"),before);
 const events=await actor.operationalActivity(row);
 assert.equal(events.rows.length,4);
 assert.deepEqual(events.rows.map(r=>r.type),['RESTORED','ARCHIVED','STATUS_UPDATED','STATUS_UPDATED']);
 const html=renderOrderIntake({route:parseOrderIntakeRoute('#/order-intake/all-orders/record/'+row.id),snapshot:{rows:[row],hasMore:false},record:{row,activity:events}});
 assert.match(html,/Change status/);assert.match(html,/Notification recipient/);assert.match(html,/Notification available in recipient inbox/);assert.doesNotMatch(html,/Edit purchase order/);
 const draft={...orderEditorDraft(),poNumber:'CP05A-'+randomUUID(),clientName:'Disposable native',company:'Fixture',industry:'Water',poDate:'2026-11-24',dateReceived:'2026-11-24',deliveryDate:'2026-12-01',poAmount:'112.00'};
 let native=await createOrderEditorSave({client:actor})(draft);
 await actor.bindRecipient(native,manager.auth.userId);
 native=await saveLifecycle({client:actor,row:native,action:'status',target:'Delayed'});
 assert.equal((await recipient.notifications()).rows.length,2);
 native=await createOrderEditorSave({client:actor,row:native})({...orderEditorDraft(native),status:'Delivered'});
 assert.equal((await recipient.notifications()).rows.length,3);
 // Changed manager invalidates the previously confirmed binding.
 native=await createOrderEditorSave({client:actor,row:native})({...orderEditorDraft(native),status:'Collected',accountManager:'Different manager'});
 assert.equal((await recipient.notifications()).rows.length,3);
 assert.equal((await actor.operationalActivity(native)).rows.find(r=>r.type==='STATUS_NOTIFICATION').delivery_state,'UNRESOLVED');
 assert.equal(sql('select count(*) from order_intake_legacy_orders'),'909');
 assert.equal(sql('select count(*) from order_intake_legacy_lifecycle'),'1');
 assert.equal(sql("select md5(string_agg(id::text||':'||md5(payload::text),',' order by id)) from order_intake_legacy_orders"),snapshotHash);
 await verifyOperationalBrowser({actor:{auth,api},recipient:{auth:other.auth,api:other.api},row});
 assert.equal(sql("select md5(string_agg(id::text||':'||md5(payload::text),',' order by id)) from order_intake_legacy_orders"),snapshotHash);
 console.log('PASS: 909 operational identities; source payload unchanged; unknown archive preserved; legacy status/archive/restore; stale and foreign denial; explicit recipient binding; two-account inbox, read acknowledgement; native workflow and editor notifications; changed manager unresolved');
}
